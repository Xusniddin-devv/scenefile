/**
 * Narration is made on this machine by an open speech model: no account, no
 * key, nothing sent anywhere. Each voice is one download (67 to 320 MB), from
 * a fixed address and checked against a known checksum before use.
 */
export interface VoiceInfo {
  language: string;
  describes: string;
  /** Where the voice comes from: what it was trained on, and under what terms. */
  basis: string;
  /** Name of the model inside the archive. */
  model: string;
  sha256: string;
  bytes: number;
  /** The kind of model. Piper voices are one small model each; Kokoro is one larger model holding several voices. */
  kind?: "kokoro";
  /** The folder the archive unpacks to, when it is not named after a Piper model. */
  folder?: string;
  /** Which voice inside a model that holds several. */
  speaker?: number;
  /** Where the archive is, when it is not among the voices. */
  url?: string;
  /** The files that must all be present, when they are not a voice's. */
  files?: string[];
}

