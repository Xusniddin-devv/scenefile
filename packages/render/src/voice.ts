const RELEASE = "https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models";

export function isVoice(name: string): name is VoiceName {
  return (VOICES as readonly string[]).includes(name);
}

/** Where voices and finished lines are kept between runs. */
export function voiceHome(env: NodeJS.ProcessEnv = process.env): string {
  return env.SCENEFILE_HOME || join(homedir(), ".cache", "scenefile");
}

function folderName(info: VoiceInfo): string {
  return info.folder ?? `vits-piper-${info.model}`;
}

function folderOf(voicesDir: string, name: VoiceName): string {
  return join(voicesDir, folderName(VOICE_CATALOG[name]));
}

/** A voice needs all of these; one missing makes the speech engine fail or crash. */
function wholeVoice(folder: string, info: VoiceInfo): boolean {
  if (info.files) return info.files.every((part) => existsSync(join(folder, part)));
  const parts = info.kind === "kokoro" ? ["model.onnx", "voices.bin", "tokens.txt"] : [`${info.model}.onnx`, "tokens.txt"];
  return [...parts, join("espeak-ng-data", "phontab")].every((part) => existsSync(join(folder, part)));
}

export function voiceInstalled(voicesDir: string, name: VoiceName): boolean {
  return wholeVoice(folderOf(voicesDir, name), VOICE_CATALOG[name]);
}

function run(command: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "ignore", "pipe"] });
    let said = "";
    child.stderr.on("data", (chunk: Buffer) => {
      said = (said + chunk.toString("utf8")).slice(-400);
    });
    child.on("error", () => reject(new Error(`The "${command}" program is needed to unpack a voice and was not found.`)));
    child.on("close", (code) =>
      code === 0 ? resolve() : reject(new Error(`Unpacking the voice failed (${command} needs bzip2 support): ${said.trim()}`)),
    );
  });
}

export interface InstallOptions {
  voicesDir: string;
  /** Replaces the download. For tests. */
  fetch?: typeof fetch;
  /** Replaces unpacking the archive with `tar`. For tests. */
  unpack?: (archive: string, into: string) => Promise<void>;
  /** Replaces the catalog entry. For tests. */
  info?: VoiceInfo;
  /** Called as the download arrives, with bytes received and bytes expected. */
  onProgress?: (received: number, total: number) => void;
  /** Seconds without a single byte arriving after which the download is given up. */
  stallSeconds?: number;
  /** What is being installed, for messages, when it is not a voice. */
  what?: string;
}

/** A download may take as long as it needs, so long as it keeps arriving. */
const STALL_SECONDS = 60;

function alive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch (cause) {
    return (cause as NodeJS.ErrnoException).code === "EPERM";
  }
}

/** Removes what installs that were killed part way left behind: up to a whole voice each. */
async function sweepInstalls(voicesDir: string): Promise<void> {
  for (const name of await readdir(voicesDir).catch(() => [] as string[])) {
    const pid = Number(/^\..+\.installing-(\d+)$/.exec(name)?.[1]);
    if (Number.isInteger(pid) && pid !== process.pid && !alive(pid)) await rm(join(voicesDir, name), { recursive: true, force: true });
  }
}

/** Downloads a voice, checks it is the file expected, and unpacks it. Does nothing if it is already there. */
export async function installVoice(name: VoiceName | (string & {}), options: InstallOptions): Promise<void> {
  const info = options.info ?? VOICE_CATALOG[name as VoiceName];
  const what = options.what ?? `the voice "${name}"`;
  const folder = folderName(info);
  const target = join(options.voicesDir, folder);
  if (wholeVoice(target, info)) return;
  await mkdir(options.voicesDir, { recursive: true });
  await sweepInstalls(options.voicesDir);
  // Everything happens in a folder of its own and is moved into place only when
  // whole, so a download or unpack that is cut short never looks like a voice.
  const work = join(options.voicesDir, `.${info.model}.installing-${process.pid}`);
  const archive = join(work, "voice.tar.bz2");
  try {
    await rm(work, { recursive: true, force: true });
    await mkdir(work);
    const stalled = new AbortController();
    const patience = (options.stallSeconds ?? STALL_SECONDS) * 1000;
    let quiet = setTimeout(() => stalled.abort(), patience);
    const heard = (): void => {
      clearTimeout(quiet);
      quiet = setTimeout(() => stalled.abort(), patience);
    };
    const response = await (options.fetch ?? fetch)(info.url ?? `${RELEASE}/${folder}.tar.bz2`, { redirect: "follow", signal: stalled.signal }).catch(
      (cause: unknown) => {
        clearTimeout(quiet);
        throw stalled.signal.aborted ? new Error(`The download for ${what} did not start. Check the connection and try again.`) : cause;
      },
    );
    if (!response.ok || !response.body) {
      clearTimeout(quiet);
      throw new Error(`The download for ${what} failed (${response.status}).`);
    }
    const hash = createHash("sha256");
    let received = 0;
    const body = Readable.fromWeb(response.body as import("node:stream/web").ReadableStream<Uint8Array>);
    stalled.signal.addEventListener("abort", () => {
      body.destroy(new Error(`The download for ${what} stopped arriving, so it was given up. Run the command again to retry.`));
    });
    body.on("data", (chunk: Buffer) => {
      heard();
      hash.update(chunk);
      received += chunk.length;
      options.onProgress?.(Math.min(received, info.bytes), info.bytes);
      if (received > info.bytes) body.destroy(new Error(`The download for ${what} is larger than expected, so it was stopped.`));
    });
    await pipeline(body, createWriteStream(archive)).finally(() => clearTimeout(quiet));
    if (hash.digest("hex") !== info.sha256) {
      throw new Error(`The download for ${what} is not the file that was expected, so it was not used.`);
    }
    await (options.unpack ?? ((file, into) => run("tar", ["-xjf", file, "-C", into])))(archive, work);
    if (!wholeVoice(join(work, folder), info)) throw new Error(`The download for ${what} arrived but could not be unpacked.`);
    // A half-made folder from an earlier version, or another process that finished first.
    if (!wholeVoice(target, info)) {
      await rm(target, { recursive: true, force: true });
      await rename(join(work, folder), target);
    }
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

/** Sound as numbers between -1 and 1. */
export interface Samples {
  samples: Float32Array;
  sampleRate: number;
}
export type Synthesize = (voiceFolder: string, model: string, text: string, info?: VoiceInfo) => Samples | Promise<Samples>;

interface Made {
  id: number;
  sampleRate?: number;
  heard?: { start: number; end: number; text: string }[];
  error?: string;
}

let helper: ChildProcess | undefined;
let asked = 0;
const waiting = new Map<number, { out: string; resolve: (sound: Samples) => void; reject: (cause: Error) => void; heard?: (parts: NonNullable<Made["heard"]>) => void }>();

/** While nothing is being made, the helper must not keep a finished command from exiting. */
function hold(busy: boolean): void {
  if (!helper) return;
  if (busy) {
    helper.ref();
    helper.channel?.ref();
  } else {
    helper.unref();
    helper.channel?.unref();
  }
}

/** The process that makes speech, started when first needed and stopped with this one. */
function speechHelper(): ChildProcess {
  if (helper) return helper;
  // Built beside this file; when run from source, as the tests do, it is in the built folder.
  const here = dirname(fileURLToPath(import.meta.url));
  const beside = join(here, "voice-worker.js");
  // Its output is discarded: the engine prints notes of its own, and a server's output is a protocol.
  const started = fork(existsSync(beside) ? beside : join(here, "..", "dist", "voice-worker.js"), [], { stdio: ["ignore", "ignore", "ignore", "ipc"] });
  const failAll = (cause: Error): void => {
    for (const pending of waiting.values()) pending.reject(cause);
    waiting.clear();
    if (helper === started) helper = undefined;
  };
  started.on("message", (made: Made) => {
    const pending = waiting.get(made.id);
    waiting.delete(made.id);
    if (waiting.size === 0) hold(false);
    if (!pending) return;
    if (made.heard && pending.heard) return pending.heard(made.heard);
    if (made.error !== undefined || !made.sampleRate) return pending.reject(new Error(made.error ?? "The speech engine returned nothing."));
    try {
      const raw = readFileSync(pending.out);
      rmSync(pending.out, { force: true });
      pending.resolve({ samples: new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4).slice(), sampleRate: made.sampleRate });
    } catch (cause) {
      pending.reject(cause instanceof Error ? cause : new Error(String(cause)));
    }
  });
  started.on("error", (cause) => failAll(cause));
  started.on("exit", () => failAll(new Error("The speech engine stopped unexpectedly. Try again.")));
  process.once("exit", () => started.kill("SIGKILL"));
  // A signal ends this process without the "exit" above running, which would leave the helper at work.
  // It is stopped first, and the signal is then left to do what it always does.
  for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"] as const) {
    process.once(signal, () => {
      started.kill("SIGKILL");
      if (process.listenerCount(signal) === 0) process.kill(process.pid, signal);
    });
  }
  helper = started;
  return started;
}

/** The real speech engine, in its own process so that making a line does not stop everything else. */
const sherpa: Synthesize = (voiceFolder, model, text, info) =>
  new Promise<Samples>((resolve, reject) => {
    asked += 1;
    const out = join(tmpdir(), `scenefile-speech-${process.pid}-${asked}.f32`);
    const process_ = speechHelper();
    waiting.set(asked, { out, resolve, reject });
    hold(true);
    process_.send({ id: asked, folder: voiceFolder, model, text, kokoro: info?.kind === "kokoro", speaker: info?.speaker ?? 0, out });
  });

/** The loudness every saved line is brought to, as a share of full scale: about -23 dB. */
const LINE_LEVEL = 0.07;

/**
 * Voices come out at different loudness, and one voice varies from line to
 * line. Each line is brought to the same level here, measured over the parts
 * where someone is speaking, so the mix can treat every line alike.
 */
function levelled(sound: Samples): Samples {
  let peak = 0;
  for (const sample of sound.samples) peak = Math.max(peak, Math.abs(sample));
  // Pauses are not counted: a line with long pauses is not a quiet line. What counts
  // as a pause is judged against the line's own loudest moment, not a fixed level.
  const floor = peak * 0.05;
  let sum = 0;
  let counted = 0;
  for (const sample of sound.samples) {
    if (Math.abs(sample) < floor) continue;
    sum += sample * sample;
    counted += 1;
  }
  if (counted === 0) return sound;
  const gain = Math.min(20, LINE_LEVEL / Math.sqrt(sum / counted));
  return { sampleRate: sound.sampleRate, samples: sound.samples.map((sample) => Math.max(-0.95, Math.min(0.95, sample * gain))) };
}

function wave({ samples, sampleRate }: Samples): Buffer {
  const file = Buffer.alloc(44 + samples.length * 2);
  file.write("RIFF", 0, "latin1");
  file.writeUInt32LE(36 + samples.length * 2, 4);
  file.write("WAVEfmt ", 8, "latin1");
  file.writeUInt32LE(16, 16);
  file.writeUInt16LE(1, 20);
  file.writeUInt16LE(1, 22);
  file.writeUInt32LE(sampleRate, 24);
  file.writeUInt32LE(sampleRate * 2, 28);
  file.writeUInt16LE(2, 32);
  file.writeUInt16LE(16, 34);
  file.write("data", 36, "latin1");
  file.writeUInt32LE(samples.length * 2, 40);
  for (let i = 0; i < samples.length; i++) {
    file.writeInt16LE(Math.round(Math.max(-1, Math.min(1, samples[i] ?? 0)) * 32767), 44 + i * 2);
  }
  return file;
}

export interface SpeakerOptions {
  /** Folder holding voices and finished lines. Defaults to `voiceHome()`. */
  home?: string;
  /** Where installed voices are, when not inside `home`. */
  voicesDir?: string;
  /** Whether a voice that is not installed may be downloaded. */
  download: boolean;
  /** Called before a download starts, so a person knows why they are waiting. */
  onDownload?: (name: VoiceName, info: VoiceInfo) => void;
  /** Replaces the speech engine. For tests. */
  synthesize?: Synthesize;
  install?: Omit<InstallOptions, "voicesDir">;
  /** The most disk the saved lines may take; the oldest are deleted to stay under it. */
  maxCacheBytes?: number;
}

const MAX_CACHE_BYTES = 500 * 1024 * 1024;

/** Deletes the oldest saved lines until the rest fit under the limit. */
async function prune(linesDir: string, limit: number, keep: string): Promise<void> {
  const files = await Promise.all(
    (await readdir(linesDir))
      .filter((name) => name.endsWith(".wav"))
      .map(async (name) => ({ path: join(linesDir, name), ...(await stat(join(linesDir, name))) })),
  );
  let total = files.reduce((sum, file) => sum + file.size, 0);
  for (const file of files.sort((a, b) => a.mtimeMs - b.mtimeMs)) {
    if (total <= limit) break;
    if (file.path === keep) continue;
    await rm(file.path, { force: true });
    await rm(`${file.path}.json`, { force: true });
    total -= file.size;
  }
}

/**
 * Makes narration. A line already said in the same voice is read back from
 * disk: the engine does not produce the same samples twice, so keeping the
 * file is also what makes a video render the same way again.
 */
export function createSpeaker(options: SpeakerOptions): Speak {
  const home = options.home ?? voiceHome();
  const voicesDir = options.voicesDir ?? join(home, "voices");
  const linesDir = join(home, "lines");
  return async (text, voice): Promise<Speech> => {
    const info = VOICE_CATALOG[voice];
    const id = createHash("sha256").update(JSON.stringify(["level-1", info.sha256, info.speaker ?? 0, text])).digest("hex").slice(0, 32);
    const file = join(linesDir, `${id}.wav`);
    const noted = `${file}.json`;
    try {
      const { seconds } = JSON.parse(await readFile(noted, "utf8")) as { seconds?: unknown };
      if (typeof seconds === "number" && Number.isFinite(seconds) && seconds > 0 && existsSync(file)) return { file, seconds };
    } catch {
      // Not made yet.
    }
    if (!voiceInstalled(voicesDir, voice)) {
      if (!options.download) {
        throw new Error(`The voice "${voice}" is not installed. Install it once with: scenefile voices install ${voice}`);
      }
      options.onDownload?.(voice, info);
      await installVoice(voice, { voicesDir, ...options.install });
    }
    const raw = await (options.synthesize ?? sherpa)(folderOf(voicesDir, voice), info.model, text, info);
    const sound = levelled(raw);
    if (sound.samples.length === 0) throw new Error("The voice produced no sound for this line. Check that it is written in the voice's language.");
    await mkdir(linesDir, { recursive: true });
    const partial = `${file}.${process.pid}.partial`;
    await writeFile(partial, wave(sound));
    await rename(partial, file);
    const seconds = sound.samples.length / sound.sampleRate;
    await writeFile(noted, JSON.stringify({ seconds, voice }));
    await prune(linesDir, options.maxCacheBytes ?? MAX_CACHE_BYTES, file).catch(() => undefined);
    return { file, seconds };
  };
}

/** Asks the helper process what is said in a file of raw sound (16 kHz, one channel, 32-bit floats). */
export function hearInHelper(sound: string, model: string, vad: string, language: string): Promise<{ start: number; end: number; text: string }[]> {
  return new Promise((resolve, reject) => {
    asked += 1;
    const process_ = speechHelper();
    waiting.set(asked, { out: "", resolve: () => undefined, reject, heard: resolve });
    hold(true);
    process_.send({ id: asked, hear: true, sound, model, vad, language });
  });
}
